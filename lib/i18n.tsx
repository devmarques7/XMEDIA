const pt = { ...ptBase, ...ptX, ...ptT, ...ptF, ...ptA, ...ptP, ...ptC, ...ptS, ...ptB };
type Dict = typeof pt;
export type Key = keyof Dict;
const en: Dict = { ...enBase, ...enX, ...enT, ...enF, ...enA, ...enP, ...enC, ...enS, ...enB };
const nl: Dict = { ...nlBase, ...nlX, ...nlT, ...nlF, ...nlA, ...nlP, ...nlC, ...nlS, ...nlB };

export const DICTS: Record<Lang, Partial<Dict>> = { pt, en, nl };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = DICTS[lang]?.[key] ?? DICTS[FALLBACK][key] ?? pt[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

type Ctx = {
  lang: Lang;
  /** Escolha explícita da pessoa (fica guardada e ganha sempre). */
  setLang: (l: Lang) => void;
  /** Sugestão (ex.: língua do cliente/convite): só se aplica se a pessoa ainda não escolheu. */
  suggestLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  locale: string;
};
const I18n = createContext<Ctx | null>(null);

const LS_LANG = "preprod:lang";
function chosen(): Lang | null {
  try {
    const saved = localStorage.getItem(LS_LANG) as Lang | null;
    if (saved && LANGS.includes(saved)) return saved;
  } catch {}
  return null;
}
/** Por omissão inglês; a escolha da pessoa (seletor de língua) fica guardada. */
const detect = (): Lang => chosen() ?? DEFAULT_LANG;

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(DEFAULT_LANG);
  useEffect(() => setLangState(detect()), []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LS_LANG, l);
    } catch {}
  }, []);
  const suggestLang = useCallback((l: Lang) => {
    if (!chosen() && LANGS.includes(l)) setLangState(l);
  }, []);
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);

  return <I18n.Provider value={{ lang, setLang, suggestLang, t, locale: LOCALE[lang] }}>{children}</I18n.Provider>;
}

export function useT() {
  const c = useContext(I18n);
  if (!c) throw new Error("LangProvider em falta");
  return c;
}
